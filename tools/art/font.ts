// Order must match the RetroFont `chars` string in src/game/fonts.ts
export const FONT_CHARS = ' !"#%&\'()*+,-./0123456789:<=>?ABCDEFGHIJKLMNOPQRSTUVWXYZx';
export const CELL_W = 7, CELL_H = 9; // 5x7 glyph with a 1px outline around it

export function drawFont(color: RGBA = P.white, outline: RGBA | null = P.ink): Pix {
  const g = new Pix(CELL_W * FONT_CHARS.length, CELL_H);
  [...FONT_CHARS].forEach((ch, i) => {
    const rows = G[ch].split(' ');
    const cell = new Pix(CELL_W, CELL_H);
    rows.forEach((r, y) => [...r].forEach((b, x) => { if (b === '1') cell.set(x + 1, y + 1, color); }));
    if (outline) cell.outline(outline, true);
    g.blit(cell, i * CELL_W, 0);
  });
  return g;
}

// Draw text straight into a Pix (for signs and the logo).
export function text(g: Pix, s: string, x: number, y: number, c: RGBA, scale = 1, spacing = 1) {
  let cx = x;
  for (const ch of s.toUpperCase()) {
    const rows = (G[ch] ?? G[' ']).split(' ');
    rows.forEach((r, yy) => [...r].forEach((b, xx) => {
      if (b === '1') g.rect(cx + xx * scale, y + yy * scale, scale, scale, c);
    }));
    cx += (5 + spacing) * scale;
  }
  return cx - x;
}
export const textWidth = (s: string, scale = 1, spacing = 1) => s.length * (5 + spacing) * scale - spacing * scale;
